# Opcode 12 is Discord's undocumented first-party member-list subscription.
# Kaede retains it for its own human clients, but bot SDKs expose only the
# documented app Gateway contract.
BOT_GATEWAY_OPS = tuple(item for item in GatewayOp if item is not GatewayOp.SUBSCRIBE_MEMBER_LIST)


def enum_ts(name: str, values: list[tuple[str, int]]) -> str:
    body = "\n".join(f"  {key} = {value}," for key, value in values)
    return f"export enum {name} {{\n{body}\n}}\n"


def permission_protocol_members() -> list[tuple[str, Permission]]:
    """Return canonical permissions plus explicit same-bit compatibility names."""

    return [(cast(str, item.name), item) for item in Permission] + list(PERMISSION_ALIASES.items())


def render() -> dict[str, str]:
    ops = "// Generated by backend/scripts/generate_protocol.py; do not edit.\n"
    ops += f"export const PROTOCOL_VERSION = {PROTOCOL_VERSION} as const;\n\n"
    ops += f"export const PRIORITY_SPEAKER_TOPIC = '{PRIORITY_SPEAKER_TOPIC}' as const;\n"
    ops += "export const PRIORITY_SPEAKER_INACTIVE_PAYLOAD = [0] as const;\n"
    ops += "export const PRIORITY_SPEAKER_ACTIVE_PAYLOAD = [1] as const;\n\n"
    ops += enum_ts("GatewayOp", [(item.name, item.value) for item in GatewayOp])
    ops += "\n" + enum_ts(
        "GatewayCloseCode", [(item.name, item.value) for item in GatewayCloseCode]
    )
    ops += "\nexport const EVENT_NAMES = [\n"
    ops += "\n".join(f"  '{event}'," for event in EVENT_NAMES)
    ops += "\n] as const;\nexport type EventName = (typeof EVENT_NAMES)[number];\n"
    ops += "\nexport const BOT_INTENT_NAMES = [\n"
    ops += "\n".join(f"  '{intent}'," for intent in BOT_INTENT_NAMES)
    ops += "\n] as const;\n"
    ops += "export type BotIntentName = (typeof BOT_INTENT_NAMES)[number];\n"
    ops += "\nexport const BOT_INTENT_ALIASES = {\n"
    ops += "\n".join(
        f"  {legacy}: '{canonical}'," for legacy, canonical in BOT_INTENT_ALIASES.items()
    )
    ops += "\n} as const satisfies Partial<Record<BotIntentName, BotIntentName>>;\n"

    permissions = "// Generated by backend/scripts/generate_protocol.py; do not edit.\n"
    permissions += f"export const PERMISSION_SCHEMA = '{PERMISSION_SCHEMA}' as const;\n\n"
    permissions += "export const Permission = {\n"
    permissions += "\n".join(
        f"  {name}: {permission.value}n," for name, permission in permission_protocol_members()
    )
    permissions += "\n} as const;\n"
    permissions += (
        "\nexport type PermissionDanger = 'normal' | 'elevated' | 'dangerous' | 'critical';\n"
    )
    permissions += "export type PermissionMetadata = {\n"
    permissions += "  permission: keyof typeof Permission;\n"
    permissions += "  bit: bigint;\n  label: string;\n  description: string;\n"
    permissions += "  group: string;\n  resourceScopes: readonly string[];\n"
    permissions += "  channelTypes: readonly number[];\n"
    permissions += "  dependencies: readonly (keyof typeof Permission)[];\n"
    permissions += "  danger: PermissionDanger;\n};\n"
    permissions += "\nexport const PERMISSION_METADATA = [\n"
    for item in PERMISSION_METADATA:
        permissions += "  {\n"
        permissions += f"    permission: '{item.permission.name}',\n"
        permissions += f"    bit: {item.permission.value}n,\n"
        permissions += f"    label: {json.dumps(item.label)},\n"
        permissions += f"    description: {json.dumps(item.description)},\n"
        permissions += f"    group: {json.dumps(item.group)},\n"
        permissions += f"    resourceScopes: {json.dumps(item.resource_scopes)},\n"
        permissions += f"    channelTypes: {json.dumps(item.channel_types)},\n"
        dependencies = [dependency.name for dependency in item.dependencies]
        permissions += f"    dependencies: {json.dumps(dependencies)},\n"
        permissions += f"    danger: '{item.danger}',\n"
        permissions += "  },\n"
    permissions += "] as const satisfies readonly PermissionMetadata[];\n"
    return {"ops.ts": ops, "permissions.ts": permissions}


def rust_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def render_rust() -> str:
    output = "// Generated by backend/scripts/generate_protocol.py; do not edit.\n"
    output += "#![allow(clippy::unreadable_literal)]\n"
    output += "use serde::{Deserialize, Serialize};\n\n"
    output += f"pub const PROTOCOL_VERSION: u16 = {PROTOCOL_VERSION};\n\n"
    output += f"pub const PRIORITY_SPEAKER_TOPIC: &str = {rust_string(PRIORITY_SPEAKER_TOPIC)};\n"
    output += "pub const PRIORITY_SPEAKER_INACTIVE_PAYLOAD: [u8; 1] = [0];\n"
    output += "pub const PRIORITY_SPEAKER_ACTIVE_PAYLOAD: [u8; 1] = [1];\n\n"
    output += f"pub const PERMISSION_SCHEMA: &str = {rust_string(PERMISSION_SCHEMA)};\n\n"
    output += "#[derive(Clone, Copy, Debug, Deserialize, Eq, Hash, PartialEq, Serialize)]\n"
    output += "#[repr(u8)]\npub enum GatewayOp {\n"
    output += "\n".join(
        f"    {item.name.title().replace('_', '')} = {item.value}," for item in GatewayOp
    )
    output += "\n}\n\n"
    output += "#[derive(Clone, Copy, Debug, Deserialize, Eq, Hash, PartialEq, Serialize)]\n"
    output += "#[repr(u16)]\npub enum GatewayCloseCode {\n"
    output += "\n".join(
        f"    {item.name.title().replace('_', '')} = {item.value}," for item in GatewayCloseCode
    )
    output += "\n}\n\n"
    output += "pub const EVENT_NAMES: &[&str] = &[\n"
    output += "\n".join(f"    {rust_string(event)}," for event in EVENT_NAMES)
    output += "\n];\n\n"
    output += "pub const BOT_INTENT_NAMES: &[&str] = &[\n"
    output += "\n".join(f"    {rust_string(intent)}," for intent in BOT_INTENT_NAMES)
    output += "\n];\n\n"
    output += "pub const BOT_INTENT_ALIASES: &[(&str, &str)] = &[\n"
    output += "\n".join(
        f"    ({rust_string(legacy)}, {rust_string(canonical)}),"
        for legacy, canonical in BOT_INTENT_ALIASES.items()
    )
    output += "\n];\n\n"
    output += "pub mod permission {\n"
    output += "\n".join(
        f"    pub const {name}: u64 = {permission.value};"
        for name, permission in permission_protocol_members()
    )
    output += "\n}\n\n"
    output += "#[derive(Clone, Copy, Debug, Eq, PartialEq)]\n"
    output += "pub struct PermissionMetadata {\n"
    output += "    pub name: &'static str,\n    pub bit: u64,\n    pub label: &'static str,\n"
    output += "    pub description: &'static str,\n    pub group: &'static str,\n"
    output += "    pub resource_scopes: &'static [&'static str],\n"
    output += "    pub channel_types: &'static [u8],\n"
    output += "    pub dependencies: &'static [u64],\n    pub danger: &'static str,\n}\n\n"
    output += "pub const PERMISSION_METADATA: &[PermissionMetadata] = &[\n"
    for item in PERMISSION_METADATA:
        scopes = ", ".join(rust_string(scope) for scope in item.resource_scopes)
        channel_types = ", ".join(str(channel_type) for channel_type in item.channel_types)
        dependencies = ", ".join(str(dependency.value) for dependency in item.dependencies)
        output += "    PermissionMetadata {\n"
        output += f"        name: {rust_string(item.permission.name or '')},\n"
        output += f"        bit: {item.permission.value},\n"
        output += f"        label: {rust_string(item.label)},\n"
        output += f"        description: {rust_string(item.description)},\n"
        output += f"        group: {rust_string(item.group)},\n"
        output += f"        resource_scopes: &[{scopes}],\n"
        output += f"        channel_types: &[{channel_types}],\n"
        output += f"        dependencies: &[{dependencies}],\n"
        output += f"        danger: {rust_string(item.danger)},\n"
        output += "    },\n"
    output += "];\n"
    return output


def dart_name(value: str) -> str:
    parts = value.lower().split("_")
    return parts[0] + "".join(part.title() for part in parts[1:])


def render_dart() -> str:
    output = "// Generated by backend/scripts/generate_protocol.py; do not edit.\n"
    output += f"const protocolVersion = {PROTOCOL_VERSION};\n\n"
    output += f"const prioritySpeakerTopic = {json.dumps(PRIORITY_SPEAKER_TOPIC)};\n"
    output += "const prioritySpeakerInactivePayload = <int>[0];\n"
    output += "const prioritySpeakerActivePayload = <int>[1];\n\n"
    output += f"const permissionSchema = {json.dumps(PERMISSION_SCHEMA)};\n\n"
    output += "enum GatewayOp {\n"
    output += "\n".join(f"  {dart_name(item.name)}({item.value})," for item in GatewayOp)
    output += "\n  ;\n\n  const GatewayOp(this.value);\n  final int value;\n}\n\n"
    output += "enum GatewayCloseCode {\n"
    output += "\n".join(
        f"  {dart_name(item.name or '')}({item.value})," for item in GatewayCloseCode
    )
    output += "\n  ;\n\n  const GatewayCloseCode(this.value);\n  final int value;\n}\n\n"
    output += "const eventNames = <String>{\n"
    output += "\n".join(f"  {json.dumps(event)}," for event in EVENT_NAMES)
    output += "\n};\n\n"
    output += "const botIntentNames = <String>{\n"
    output += "\n".join(f"  {json.dumps(intent)}," for intent in BOT_INTENT_NAMES)
    output += "\n};\n\n"
    output += "const botIntentAliases = <String, String>{\n"
    output += "\n".join(
        f"  {json.dumps(legacy)}: {json.dumps(canonical)},"
        for legacy, canonical in BOT_INTENT_ALIASES.items()
    )
    output += "\n};\n\n"
    output += "abstract final class Permission {\n"
    output += "\n".join(
        f"  static const {dart_name(name)} = {permission.value};"
        for name, permission in permission_protocol_members()
    )
    output += "\n}\n\n"
    output += "enum PermissionDanger { normal, elevated, dangerous, critical }\n\n"
    output += "class PermissionMetadata {\n"
    output += "  const PermissionMetadata({\n"
    output += "    required this.name,\n    required this.bit,\n"
    output += "    required this.label,\n    required this.description,\n"
    output += "    required this.group,\n    required this.resourceScopes,\n"
    output += "    required this.channelTypes,\n    required this.dependencies,\n"
    output += "    required this.danger,\n  });\n\n"
    output += "  final String name;\n  final int bit;\n  final String label;\n"
    output += "  final String description;\n  final String group;\n"
    output += "  final List<String> resourceScopes;\n"
    output += "  final List<int> channelTypes;\n  final List<int> dependencies;\n"
    output += "  final PermissionDanger danger;\n}\n\n"
    output += "const permissionMetadata = <PermissionMetadata>[\n"
    for item in PERMISSION_METADATA:
        dependencies = ", ".join(str(value.value) for value in item.dependencies)
        output += "  PermissionMetadata(\n"
        output += f"    name: {json.dumps(item.permission.name or '')},\n"
        output += f"    bit: {item.permission.value},\n"
        output += f"    label: {json.dumps(item.label)},\n"
        description = json.dumps(item.description)
        if len(f"    description: {description},") <= 80:
            output += f"    description: {description},\n"
        else:
            output += "    description:\n"
            output += f"        {description},\n"
        output += f"    group: {json.dumps(item.group)},\n"
        output += f"    resourceScopes: {json.dumps(item.resource_scopes)},\n"
        output += f"    channelTypes: {json.dumps(item.channel_types)},\n"
        output += f"    dependencies: <int>[{dependencies}],\n"
        output += f"    danger: PermissionDanger.{item.danger},\n"
        output += "  ),\n"
    output += "];\n"
    return output


def render_python() -> str:
    output = "# Generated by backend/scripts/generate_protocol.py; do not edit.\n"
    output += "from enum import IntEnum, IntFlag\n\n"
    output += f"PROTOCOL_VERSION = {PROTOCOL_VERSION}\n\n\n"
    output += f"PRIORITY_SPEAKER_TOPIC = {json.dumps(PRIORITY_SPEAKER_TOPIC)}\n"
    output += (
        f'PRIORITY_SPEAKER_INACTIVE_PAYLOAD = b"\\x{PRIORITY_SPEAKER_INACTIVE_PAYLOAD[0]:02x}"\n'
    )
    output += (
        f'PRIORITY_SPEAKER_ACTIVE_PAYLOAD = b"\\x{PRIORITY_SPEAKER_ACTIVE_PAYLOAD[0]:02x}"\n\n\n'
    )
    output += f"PERMISSION_SCHEMA = {json.dumps(PERMISSION_SCHEMA)}\n\n\n"
    output += "class GatewayOp(IntEnum):\n"
    output += "\n".join(f"    {item.name} = {item.value}" for item in BOT_GATEWAY_OPS)
    output += "\n\n\n"
    output += "class Permission(IntFlag):\n"
    output += "\n".join(
        f"    {name} = {permission.value}" for name, permission in permission_protocol_members()
    )
    output += "\n\n\n"
    output += f"ALL_PERMISSIONS = {sum(item.value for item in Permission)}\n\n"
    output += "EVENT_NAMES = (\n"
    output += "\n".join(f"    {json.dumps(event)}," for event in EVENT_NAMES)
    output += "\n)\n\n"
    output += "BOT_INTENT_NAMES = (\n"
    output += "\n".join(f"    {json.dumps(intent)}," for intent in BOT_INTENT_NAMES)
    output += "\n)\n\n"
    output += "BOT_INTENT_ALIASES = {\n"
    output += "\n".join(
        f"    {json.dumps(legacy)}: {json.dumps(canonical)},"
        for legacy, canonical in BOT_INTENT_ALIASES.items()
    )
    output += "\n}\n"
    return output


def main() -> None:
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for filename, content in render().items():
        (OUTPUT / filename).write_text(content, encoding="utf-8")
    RUST_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    RUST_OUTPUT.write_text(render_rust(), encoding="utf-8")
    DART_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    DART_OUTPUT.write_text(render_dart(), encoding="utf-8")
    PYTHON_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    PYTHON_OUTPUT.write_text(render_python(), encoding="utf-8")


if __name__ == "__main__":
    main()
